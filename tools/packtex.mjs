// Pack downloaded CC0 Poly Haven textures (polyhaven.com) into textures.js as 512px JPEG data URIs,
// so the page works from file:// (WebGL can't read file:// images directly).
//   node tools/packtex.mjs <srcDir> name1 name2 ...      (expects <name>_Diffuse.jpg and <name>_nor_gl.jpg)
import { chromium } from 'playwright-core';
import fs from 'node:fs';
import path from 'node:path';
const [src, ...names] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'msedge' });
const p = await b.newPage();
const out = {};
for (const n of names) for (const [m, key] of [['Diffuse', ''], ['nor_gl', 'N']]) {
  const f = path.join(src, `${n}_${m}.jpg`);
  if (!fs.existsSync(f)) continue;
  const data = 'data:image/jpeg;base64,' + fs.readFileSync(f).toString('base64');
  out[n + key] = await p.evaluate(async (data) => {
    const img = new Image(); img.src = data; await img.decode();
    const c = document.createElement('canvas'); c.width = c.height = 512;
    c.getContext('2d').drawImage(img, 0, 0, 512, 512);
    return c.toDataURL('image/jpeg', 0.82);
  }, data);
}
await b.close();
const js = '/* CC0 textures from Poly Haven (polyhaven.com): ' + names.join(', ') + '. 512px diffuse + OpenGL normal maps. Generated by tools/packtex.mjs */\n' +
  'window.KNIGHT_TEX = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync('textures.js', js);
console.log('textures.js', (js.length / 1024).toFixed(0) + ' KB', Object.keys(out).join(' '));
