// Pack CC0 Poly Haven textures (polyhaven.com) for the village / forest into village/phtex.js as 512px JPEG data URIs
// (the game runs from file://, WebGL cannot read file:// images directly).
//   node tools/packvtex.mjs <srcDir>
// <srcDir> holds <id>_Diffuse.jpg + <id>_nor_gl.jpg (1k downloads from dl.polyhaven.org).
// Diffuse maps get a tile-safe "painterly" pass (Kuwahara filter = flat painted strokes instead of photo grain,
// then a saturation / contrast lift) so the photo textures sit with the hand-painted look of the game.
import { chromium } from 'playwright-core';
import fs from 'node:fs';
import path from 'node:path';
const src = process.argv[2];
if (!src) { console.log('usage: node tools/packvtex.mjs <srcDir>'); process.exit(1); }
// key -> [poly haven id, kuwahara radius, saturation, contrast, brightness]
const SET = {
  bark: ['jolcham_oak_bark_01', 3, 1.15, 1.08, 1.0],
  floor: ['forest_leaves_02', 3, 1.2, 1.05, 1.0],
  meadow: ['forrest_ground_01', 2, 1.25, 1.04, 1.0],
  mossrock: ['mossy_rock', 3, 1.15, 1.06, 1.0],
  // ground layers of the open world (world/terrain.js): diffuse only (6th field = no normal map)
  roaddirt: ['park_dirt', 2, 1.15, 1.04, 1.0, true],
  trail: ['rocky_trail', 2, 1.1, 1.04, 1.0, true],
  lgrass: ['leafy_grass', 2, 1.25, 1.05, 1.0, true],
  sand: ['coast_sand_01', 2, 1.1, 1.05, 1.05, true],
};
const b = await chromium.launch({ channel: 'msedge' });
const p = await b.newPage();
const out = {};
for (const [key, [id, kr, sat, con, bri, noN]] of Object.entries(SET)) {
  for (const [suffix, isN] of [['Diffuse', false], ['nor_gl', true]]) {
    if (isN && noN) continue;
    const f = path.join(src, `${id}_${suffix}.jpg`);
    if (!fs.existsSync(f)) { console.log('missing', f); continue; }
    const data = 'data:image/jpeg;base64,' + fs.readFileSync(f).toString('base64');
    out[key + (isN ? 'N' : '')] = await p.evaluate(async ([data, isN, kr, sat, con, bri]) => {
      const img = new Image(); img.src = data; await img.decode();
      const S = 512, c = document.createElement('canvas'); c.width = c.height = S;
      const g = c.getContext('2d'); g.imageSmoothingQuality = 'high'; g.drawImage(img, 0, 0, S, S);
      const id = g.getImageData(0, 0, S, S), d = id.data;
      const at = (x, y) => (((y + S) % S) * S + ((x + S) % S)) * 4;
      if (isN) {   // normals: 3x3 wrap blur (removes photo micro-noise, keeps the big relief)
        const o = new Uint8ClampedArray(d.length);
        for (let y = 0; y < S; y++) for (let x = 0; x < S; x++) {
          for (let ch = 0; ch < 3; ch++) { let s = 0; for (let j = -1; j <= 1; j++) for (let i = -1; i <= 1; i++) s += d[at(x + i, y + j) + ch]; o[(y * S + x) * 4 + ch] = s / 9; }
          o[(y * S + x) * 4 + 3] = 255;
        }
        id.data.set(o);
      } else {     // Kuwahara (4 quadrants, radius kr, wrap) -> painterly strokes
        const lum = new Float32Array(S * S);
        for (let i = 0; i < S * S; i++) lum[i] = d[i * 4] * 0.3 + d[i * 4 + 1] * 0.59 + d[i * 4 + 2] * 0.11;
        const o = new Uint8ClampedArray(d.length);
        const Q = [[-kr, 0, -kr, 0], [0, kr, -kr, 0], [-kr, 0, 0, kr], [0, kr, 0, kr]];
        for (let y = 0; y < S; y++) for (let x = 0; x < S; x++) {
          let best = 1e9, br = 0, bg = 0, bb = 0;
          for (const [x0, x1, y0, y1] of Q) {
            let n = 0, s = 0, s2 = 0, r = 0, gg = 0, bl = 0;
            for (let j = y0; j <= y1; j++) for (let i = x0; i <= x1; i++) { const k = at(x + i, y + j), l = lum[k >> 2]; s += l; s2 += l * l; r += d[k]; gg += d[k + 1]; bl += d[k + 2]; n++; }
            const v = s2 / n - (s / n) * (s / n);
            if (v < best) { best = v; br = r / n; bg = gg / n; bb = bl / n; }
          }
          // saturation / contrast / brightness lift around the mid grey
          const L = br * 0.3 + bg * 0.59 + bb * 0.11;
          const f = (v) => ((L + (v - L) * sat) - 128) * con + 128;
          const k = (y * S + x) * 4; o[k] = f(br) * bri; o[k + 1] = f(bg) * bri; o[k + 2] = f(bb) * bri; o[k + 3] = 255;
        }
        id.data.set(o);
      }
      g.putImageData(id, 0, 0);
      return c.toDataURL('image/jpeg', isN ? 0.86 : 0.84);
    }, [data, isN, kr, sat, con, bri]);
  }
}
await b.close();
const ids = Object.values(SET).map((s) => s[0]).join(', ');
const js = '/* CC0 textures from Poly Haven (polyhaven.com): ' + ids + '.\n * 512px, diffuse with a painterly (Kuwahara) pass + OpenGL normal maps. Generated by tools/packvtex.mjs */\n' +
  'window.VILLAGE_PH = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.resolve(import.meta.dirname, '..', 'village', 'phtex.js'), js);
console.log('village/phtex.js', (js.length / 1024).toFixed(0) + ' KB', Object.keys(out).join(' '));
